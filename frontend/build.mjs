import { build } from "esbuild";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const output = new URL("../src/pytred/static/", import.meta.url);
const result = await build({
  absWorkingDir: new URL(".", import.meta.url).pathname,
  entryPoints: ["widget.js"],
  outfile: new URL("widget.js", output).pathname,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "inline",
  metafile: true,
});
for (const file of Object.values(result.metafile.outputs)) {
  if (file.imports.length) throw new Error("Widget bundle must not import external assets");
}
await copyFile(new URL("widget.css", import.meta.url), new URL("widget.css", output));
const notices = [
  "The pytred source and wheel distributions bundle the following JavaScript\n" +
  "libraries in widget.js. File paths below are relative to this directory.\n" +
  "Generated by frontend/build.mjs; do not edit manually.\n",
];
for (const name of ["cytoscape", "@dagrejs/dagre", "@dagrejs/graphlib"]) {
  const location = new URL(`node_modules/${name}/`, import.meta.url);
  const pkg = JSON.parse(await readFile(new URL("package.json", location), "utf8"));
  const licenseDirectory = new URL(`licenses/${name}/`, output);
  await mkdir(licenseDirectory, { recursive: true });
  await copyFile(new URL("LICENSE", location), new URL("LICENSE", licenseDirectory));
  notices.push(
    `Name: ${name}\nVersion: ${pkg.version}\nFiles: widget.js\n` +
    `License: ${pkg.license}\nFor license text, see licenses/${name}/LICENSE\n`,
  );
}
await writeFile(new URL("LICENSES_bundled.txt", output), notices.join("\n"));
